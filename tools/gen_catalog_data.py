#!/usr/bin/env python3
"""Step B generator: approved category table -> PluginCatalogData.java
(stable keys, aliases, categories, curated/synth flags), catalog category
rewrites (A3), and the single key-based blacklist.json.

Golden input : WIP/audit_r24/approved_categories.json (Hery-approved)
Runtime output: app/src/main/java/com/kancrutt/gigginggear/PluginCatalogData.java
Also writes  : WIP/audit_r24/category_counts.txt
Token heuristics live ONLY in tools/gen_category_map.py (candidate review file).
"""

import json, re, os, glob, collections

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
A = os.path.join(ROOT, "app/src/main/assets")
OUT_DIR = os.path.join(ROOT, "app/src/main/java/com/kancrutt/gigginggear")
WIP = os.path.join(ROOT, "WIP/audit_r24")
GOLD = json.load(open(os.path.join(WIP, "approved_categories.json")))["entries"]


def jesc(s):
    return (s or "").replace("\\", "\\\\").replace('"', '\\"')


def lv2_aliases(lib, catalog_name):
    """Per-entry aliases: catalog name + the bundle json describing THIS
    plugin. A bundle holds many plugins (rkrlv2.so has 40+), so bundle-wide
    aliases would make every name ambiguous; ttl doap:name is used only for
    single-plugin bundles."""
    d = os.path.join(A, "lv2", lib)
    aliases = {catalog_name}
    jsons = sorted(glob.glob(os.path.join(d, "*.json")))
    for f in jsons:
        try:
            j = json.load(open(f))
            m = j.get("-1", {})
            if isinstance(m, dict) and m.get("pluginName") == catalog_name:
                aliases.add(m["pluginName"])
        except Exception:
            pass
    ttls = sorted(glob.glob(os.path.join(d, "*.ttl")))
    if len(jsons) <= 1 and len(ttls) == 1:
        try:
            t = open(ttls[0], encoding="utf-8", errors="replace").read()
            for m in re.finditer(r'doap:name\s+"([^"]+)"', t):
                aliases.add(m.group(1))
        except Exception:
            pass
    return aliases


# ---- collect entries in stable order ----
ladspa = json.load(open(os.path.join(A, "all_plugins.json")))
lv2 = json.load(open(os.path.join(A, "lv2_plugins.json")))

entries = []  # dicts
by_key = {}
blacklist_raw = json.load(open(os.path.join(A, "blacklist.json")))
blacklist_old = set(blacklist_raw.get("keys", []))
blacklist_names = set()
for k in blacklist_raw:
    if k not in ("keys", "libs", "_comment") and "|" not in str(k):
        blacklist_names.add(str(k).lower())
new_bl_keys = list(blacklist_old)


def add(src, lib, ident, idx, name):
    key = f"{src}|{lib}|{ident}"
    if key in by_key:
        raise SystemExit(f"DUPLICATE STABLE KEY: {key}")
    g = GOLD[key]
    aliases = set()
    aliases.add(name)
    if src == "LV2":
        aliases |= lv2_aliases(lib, name)
    aliases.add(name.lower())
    e = {
        "key": key,
        "name": name,
        "lib": lib,
        "idx": idx,
        "src": src,
        "cat": g["cat"],
        "curated": g["curated"],
        "synth": g["synth"],
        "aliases": sorted(a for a in aliases if a),
    }
    entries.append(e)
    by_key[key] = e
    if key in blacklist_old or name.lower() in blacklist_names:
        if key not in new_bl_keys:
            new_bl_keys.append(key)


for k, e in ladspa.items():
    if isinstance(e, dict) and e.get("name"):
        add("LADSPA", e["library"], e["id"], e["plugin"], e["name"])
for k, e in lv2.items():
    if isinstance(e, dict) and e.get("name"):
        add("LV2", e["library"], e["index"], e["index"], e["name"])

assert len(entries) == len(GOLD), f"{len(entries)} entries vs golden {len(GOLD)}"
missing = set(GOLD) - set(by_key)
assert not missing, f"golden keys missing from catalogs: {sorted(missing)[:5]}"

# name -> entry indices (collision-aware: flanger LADSPA vs LV2)
name_index = collections.defaultdict(set)
for i, e in enumerate(entries):
    for a in e["aliases"]:
        name_index[a].add(i)

# ---- emit PluginCatalogData.java ----
L = []
L.append("package com.kancrutt.gigginggear;")
L.append("")
L.append("import java.util.HashMap;")
L.append("import java.util.Map;")
L.append("")
L.append(
    "/** GENERATED by tools/gen_catalog_data.py from WIP/audit_r24/approved_categories.json"
)
L.append(" *  (Hery-approved 2026-10-11). DO NOT EDIT BY HAND.")
L.append(" *  One row per catalog entry with a STABLE key: source|lib|index")
L.append(" *  (LADSPA uses UniqueID as identity, LV2 uses the descriptor index).")
L.append(" *  Category = approved canonical enum name; curated/synth flags drive the")
L.append(
    " *  single curation gate (visible = curated AND NOT blacklisted AND NOT synth). */"
)
L.append("public final class PluginCatalogData {")
L.append("    private PluginCatalogData() {}")
L.append(f"    public static final int COUNT = {len(entries)};")
for field in ["KEY", "NAME", "LIB", "SOURCE", "CATEGORY"]:
    L.append(f"    public static final String[] {field} = new String[COUNT];")
L.append("    public static final int[] IDX = new int[COUNT];")
L.append("    public static final boolean[] CURATED = new boolean[COUNT];")
L.append("    public static final boolean[] SYNTH = new boolean[COUNT];")
L.append("    private static final String[][] ALIASES = new String[COUNT][];")
for i, e in enumerate(entries):
    al = ", ".join(f'"{jesc(a)}"' for a in e["aliases"])
    L.append(
        f'    static {{ KEY[{i}]="{jesc(e["key"])}"; NAME[{i}]="{jesc(e["name"])}"; '
        f'LIB[{i}]="{jesc(e["lib"])}"; IDX[{i}]={e["idx"]}; SOURCE[{i}]="{e["src"]}"; '
        f'CATEGORY[{i}]="{e["cat"]}"; CURATED[{i}]={str(e["curated"]).lower()}; '
        f"SYNTH[{i}]={str(e['synth']).lower()}; ALIASES[{i}]=new String[]{{{al}}}; }}"
    )
# maps
L.append("    private static final Map<String, Integer> KEY_INDEX = new HashMap<>();")
L.append("    private static final Map<String, int[]> NAME_INDEX = new HashMap<>();")
L.append("    static {")
L.append("        for (int i = 0; i < COUNT; i++) KEY_INDEX.put(KEY[i], i);")
L.append("    }")
L.append("    static {")
L.append("        Map<String, java.util.List<Integer>> acc = new HashMap<>();")
L.append("        for (int i = 0; i < COUNT; i++)")
L.append("            for (String a : ALIASES[i]) {")
L.append("                String k = a.toLowerCase(java.util.Locale.US).trim();")
L.append("                java.util.List<Integer> l = acc.get(k);")
L.append(
    "                if (l == null) { l = new java.util.ArrayList<>(); acc.put(k, l); }"
)
L.append("                if (!l.contains(i)) l.add(i);")
L.append("            }")
L.append(
    "        for (Map.Entry<String, java.util.List<Integer>> en : acc.entrySet()) {"
)
L.append("            int[] arr = new int[en.getValue().size()];")
L.append(
    "            for (int j = 0; j < arr.length; j++) arr[j] = en.getValue().get(j);"
)
L.append("            NAME_INDEX.put(en.getKey(), arr);")
L.append("        }")
L.append("    }")
L.append(
    "    public static int indexOfKey(String key) { Integer i = KEY_INDEX.get(key); return i == null ? -1 : i; }"
)
L.append("    /** All entry indices a name/alias resolves to (empty when unknown);")
L.append('     *  size>1 = ambiguous (e.g. LADSPA "Flanger" vs LV2 "Gx_flanger"). */')
L.append("    public static int[] indicesForName(String name) {")
L.append("        if (name == null) return new int[0];")
L.append(
    "        int[] r = NAME_INDEX.get(name.toLowerCase(java.util.Locale.US).trim());"
)
L.append("        return r == null ? new int[0] : r;")
L.append("    }")
L.append("}")
open(os.path.join(OUT_DIR, "PluginCatalogData.java"), "w").write("\n".join(L) + "\n")


# ---- A3: rewrite category fields from the approved table ----
def rewrite(path, is_lv2, is_wip=False):
    d = json.load(open(path))
    n = 0
    if is_lv2:
        for k, e in d.items():
            if isinstance(e, dict) and e.get("name"):
                key = f"LV2|{e['library']}|{e['index']}"
                if "category" in e:
                    new = by_key[key]["cat"]
                    if e["category"] != new:
                        n += 1
                    e["category"] = new
    else:
        for p in d["plugins"]:
            key = f"{p.get('format', 'LV2')}|{p['library']}|{p.get('id')}"
            if key not in by_key:
                key = f"LV2|{p['library']}|{next((e['index'] for e in lv2.values() if e.get('name') == p['name']), None)}"
            e = by_key[key]
            if p.get("category") != e["cat"]:
                n += 1
            p["category"] = e["cat"]
    # preserve the source formatting: lv2_plugins.json is pretty-printed,
    # the curated catalogs are compact
    if path.endswith("lv2_plugins.json") or is_wip:
        json.dump(d, open(path, "w"), indent=2, ensure_ascii=False)
    else:
        json.dump(d, open(path, "w"), ensure_ascii=False, separators=(",", ":"))
    return n


n1 = rewrite(os.path.join(A, "lv2_plugins.json"), True)
n2 = rewrite(os.path.join(ROOT, "WIP/guitar_plugins_catalog.json"), False, is_wip=True)
# assets curated catalog is compact (no spaces)
p = os.path.join(A, "guitar_plugins_catalog.json")
raw = open(p, encoding="utf-8").read()
d = json.loads(raw)
n3 = 0
for ent in d["plugins"]:
    key = None
    for e in lv2.values():
        if e.get("name") == ent["name"]:
            key = f"LV2|{e['library']}|{e['index']}"
            break
    if key is None:
        continue
    if ent.get("category") != by_key[key]["cat"]:
        n3 += 1
    ent["category"] = by_key[key]["cat"]
open(p, "w", encoding="utf-8").write(
    json.dumps(d, ensure_ascii=False, separators=(",", ":"))
)

# ---- single blacklist file, keyed by stable key ----
bl = {
    "_comment": "Step B: one blacklist, keyed by stable key (source|lib|index) or by lib.",
    "keys": sorted(set(new_bl_keys)),
    "libs": [],
}
json.dump(bl, open(os.path.join(A, "blacklist.json"), "w"), indent=1)

cnt = collections.Counter(e["cat"] for e in entries)
before = {
    "DISTORTION": 99,
    "MODULATION": 50,
    "EQ": 38,
    "DELAY": 34,
    "AMP": 32,
    "UTILITY": 31,
    "DYNAMICS": 27,
    "PITCH": 20,
    "REVERB": 18,
    "CABINET": 10,
    "WAH": 7,
    "GATE": 4,
}
open(os.path.join(WIP, "category_counts.txt"), "w").write(
    "BEFORE (Phase 0) -> AFTER (approved)\n"
    + "\n".join(
        f"{k:12s} {before.get(k, 0):4d} -> {cnt.get(k, 0):4d}"
        for k in sorted(set(before) | set(cnt), key=lambda x: -cnt.get(x, 0))
    )
    + f"\ntotal: {sum(before.values())} -> {sum(cnt.values())}\n"
)
print("generated PluginCatalogData.java entries:", len(entries))
print(
    "cat_json rewrites: lv2_plugins=%d, WIP curated=%d, assets curated=%d"
    % (n1, n2, n3)
)
print("blacklist.json keys:", bl["keys"])
print(open(os.path.join(WIP, "category_counts.txt")).read())
